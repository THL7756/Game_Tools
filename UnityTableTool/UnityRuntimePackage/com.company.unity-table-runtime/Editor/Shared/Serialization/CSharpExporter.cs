        public static string Export(TableDocument document, bool includeRuntimeAdapter = false)
        {
            var invalidName = document.Schema.Fields
                .SelectMany(field => FieldNameValidator.Validate(field, document.SourceName))
                .FirstOrDefault();
            if (invalidName is not null)
                throw new InvalidOperationException($"{invalidName.Code}: {invalidName.Message} {invalidName.Suggestion}");

            var builder = new StringBuilder();
            builder.AppendLine("// 用途：由 UnityTableTool 根据配置表结构生成的数据类。");
            builder.AppendLine($"// 编写日期：{DateTime.Now:yyyy-MM-dd}");
            builder.AppendLine("// 作者：UnityTableTool。");
            builder.AppendLine("// Generated by UnityTableTool. Do not edit.");
            builder.AppendLine();
            var hasUnityTypes = document.Schema.Fields.Any(field => ContainsUnityType(field.Type));
            var hasComplexTypes = document.Schema.Fields.Any(field => field.Type.IsComplex);
            if (includeRuntimeAdapter)
            {
                builder.AppendLine("using Company.UnityTableRuntime;");
                builder.AppendLine("using Company.UnityTableRuntime.Shared;");
                builder.AppendLine("using System.Linq;");
            }
            if (includeRuntimeAdapter || hasComplexTypes)
                builder.AppendLine("using System.Collections.Generic;");
            if (hasUnityTypes)
                builder.AppendLine("using UnityEngine;");
            if (includeRuntimeAdapter || hasUnityTypes || hasComplexTypes)
                builder.AppendLine();

            builder.AppendLine("#nullable enable");
            var enumNames = new HashSet<string>(StringComparer.Ordinal);
            foreach (var field in document.Schema.Fields)
            foreach (var enumType in EnumerateEnumTypes(field.Type, field.Name))
                if (enumNames.Add(enumType.Name))
                    AppendEnum(builder, enumType.Name, enumType.Values);

            builder.AppendLine($"public sealed class {document.Schema.Name}Data");
            builder.AppendLine("{");
            foreach (var field in document.Schema.Fields)
                builder.AppendLine($"    public {ToCSharpType(field.Type, field.Name)} {ToPascal(field.Name)};");

            foreach (var field in document.Schema.Fields.Where(field => field.Type.IsComplex))
                AppendComplexTypes(builder, field.Type, ToComplexTypeName(field.Name, field.Type), "    ");
            builder.AppendLine("}");

            if (includeRuntimeAdapter)
                AppendRuntimeAdapter(builder, document);
            return builder.ToString();
        }

        public static bool IsValidEnumMember(string value) =>
            IsIdentifier(value) && !IsCSharpKeyword(value);

        private static void AppendEnum(StringBuilder builder, string enumName, IReadOnlyList<string> values)
        {
            builder.AppendLine($"public enum {enumName}");
            builder.AppendLine("{");
            foreach (var value in values)
            {
                if (!IsValidEnumMember(value))
                    throw new InvalidOperationException($"枚举成员“{value}”不是合法的 C# 标识符。");
                builder.AppendLine($"    {value},");
            }
            builder.AppendLine("}");
        }

        private static void AppendComplexTypes(StringBuilder builder, TypeDescriptor type, string typeName, string indent)
        {
            if (type.IsLocalization)
            {
                builder.AppendLine();
                builder.AppendLine($"{indent}public sealed class {typeName}");
                builder.AppendLine($"{indent}{{");
                builder.AppendLine($"{indent}    public string Key;");
                builder.AppendLine($"{indent}}}");
                return;
            }

            if (type.IsBeans)
            {
                builder.AppendLine();
                builder.AppendLine($"{indent}public sealed class {typeName}");
                builder.AppendLine($"{indent}{{");
                foreach (var field in type.BeanFields ?? Array.Empty<BeanFieldDescriptor>())
                    builder.AppendLine($"{indent}    public {ToCSharpType(field.Type, field.Name)} {ToPascal(field.Name)};");
                foreach (var field in type.BeanFields ?? Array.Empty<BeanFieldDescriptor>())
                    if (field.Type.IsComplex)
                        AppendComplexTypes(builder, field.Type, ToComplexTypeName(field.Name, field.Type), indent + "    ");
                builder.AppendLine($"{indent}}}");
                return;
            }

            if (type.IsMap)
            {
                builder.AppendLine();
                builder.AppendLine($"{indent}public sealed class {typeName}");
                builder.AppendLine($"{indent}{{");
                builder.AppendLine($"{indent}    public {ToCSharpType(type.KeyType!, "key")} Key;");
                builder.AppendLine($"{indent}    public {ToCSharpType(type.ValueType!, "text")} Text;");
                builder.AppendLine($"{indent}    public {ToCSharpType(type.BeanType!, "bean")} Bean;");
                if (type.ValueType!.IsComplex)
                    AppendComplexTypes(builder, type.ValueType, ToComplexTypeName("text", type.ValueType), indent + "    ");
                if (type.BeanType!.IsComplex)
                    AppendComplexTypes(builder, type.BeanType, ToComplexTypeName("bean", type.BeanType), indent + "    ");
                builder.AppendLine($"{indent}}}");
            }
        }


        private static string ToCSharpType(TypeDescriptor type, string fieldName)
        {
            var result = type.BaseType switch
            {
                "int" => "int",
                "long" => "long",
                "float" => "float",
                "double" => "double",
                "bool" => "bool",
                "string" => "string",
                "enum" => ToEnumName(fieldName),
                "localization" or "beans" => ToComplexTypeName(fieldName, type),
                "map" => $"Dictionary<{ToCSharpType(type.KeyType!, "key")}, {ToComplexTypeName(fieldName, type)}>",
                _ => type.BaseType
            };
            return result + string.Concat(Enumerable.Repeat("[]", type.Dimensions));
        }

        private static string ToComplexTypeName(string fieldName, TypeDescriptor type) =>
            ToPascal(fieldName) + (type.IsLocalization ? "Value" : type.IsBeans ? "Bean" : "Entry");


        private static string ToEnumName(FieldSchema field) => $"{ToPascal(field.Name)}Value";
        private static string ToEnumName(string fieldName) => $"{ToPascal(fieldName)}Value";
        private static bool IsUnityType(string baseType) => baseType is "Vector2" or "Vector3" or "Vector4" or "Color" or "Quaternion";
        private static bool ContainsUnityType(TypeDescriptor type)
        {
            if (IsUnityType(type.BaseType))
                return true;
            if (type.IsBeans)
                return (type.BeanFields ?? Array.Empty<BeanFieldDescriptor>()).Any(field => ContainsUnityType(field.Type));
            if (type.IsMap)
                return ContainsUnityType(type.KeyType!) || ContainsUnityType(type.ValueType!) || ContainsUnityType(type.BeanType!);
            return false;
        }

        private static IEnumerable<(string BaseType, int Dimensions)> EnumerateUnityTypes(TypeDescriptor type)
        {
            if (IsUnityType(type.BaseType))
                yield return (type.BaseType, type.Dimensions);
            if (type.IsBeans)
                foreach (var field in type.BeanFields ?? Array.Empty<BeanFieldDescriptor>())
                foreach (var item in EnumerateUnityTypes(field.Type))
                    yield return item;
            if (type.IsMap)
            {
                foreach (var item in EnumerateUnityTypes(type.KeyType!))
                    yield return item;
                foreach (var item in EnumerateUnityTypes(type.ValueType!))
                    yield return item;
                foreach (var item in EnumerateUnityTypes(type.BeanType!))
                    yield return item;
            }
        }

        private static IEnumerable<(string Name, IReadOnlyList<string> Values)> EnumerateEnumTypes(TypeDescriptor type, string fieldName)
        {
            if (type.IsEnum)
                yield return (ToEnumName(fieldName), type.EnumValues ?? Array.Empty<string>());
            if (type.IsBeans)
                foreach (var field in type.BeanFields ?? Array.Empty<BeanFieldDescriptor>())
                foreach (var item in EnumerateEnumTypes(field.Type, field.Name))
                    yield return item;
            if (type.IsMap)
            {
                foreach (var item in EnumerateEnumTypes(type.KeyType!, "key"))
                    yield return item;
                foreach (var item in EnumerateEnumTypes(type.ValueType!, "text"))
                    yield return item;
                foreach (var item in EnumerateEnumTypes(type.BeanType!, "bean"))
                    yield return item;
            }
        }
        private static string ToComponentArrayType(int dimensions) => "float" + string.Concat(Enumerable.Repeat("[]", dimensions + 1));
        private static string ToUnityArrayType(string baseType, int dimensions) => baseType + string.Concat(Enumerable.Repeat("[]", dimensions));
        private static string Escape(string value) => value.Replace("\\", "\\\\").Replace("\"", "\\\"");
        private static bool IsCSharpKeyword(string value) => value switch
        {
            "class" or "namespace" or "public" or "private" or "protected" or "internal" or "void"
                or "int" or "long" or "float" or "double" or "bool" or "string" or "enum" or "new" => true,
            _ => false
        };
        private static bool IsIdentifier(string value) =>
            !string.IsNullOrWhiteSpace(value)
            && (char.IsLetter(value[0]) || value[0] == '_')
            && value.Skip(1).All(character => char.IsLetterOrDigit(character) || character == '_');
        private static string ToPascal(string name) => string.IsNullOrEmpty(name) ? name : char.ToUpperInvariant(name[0]) + name[1..];
    }
}
